using Microsoft.Extensions.Options;
using Roslyn.Workbench.Mcp.Workspace.Configuration;

namespace Roslyn.Workbench.Mcp.Workspace.Test.Resolution;

public sealed class GeneratedSourceClassifierTests : IDisposable
{
    private readonly AdhocWorkspace _workspace;
    private readonly Mock<IWorkspacePathComparison> _pathComparison;
    private readonly Mock<IFileSystem> _fileSystem;
    private readonly Mock<IPath> _path;

    public GeneratedSourceClassifierTests()
    {
        _workspace = new AdhocWorkspace();
        _pathComparison = new Mock<IWorkspacePathComparison>();
        _fileSystem = new Mock<IFileSystem>();
        _path = new Mock<IPath>();
        _fileSystem.SetupGet(item => item.Path).Returns(_path.Object);
        _pathComparison
            .Setup(item => item.GetComparison(It.IsAny<string>()))
            .Returns(StringComparison.Ordinal);

        _path
            .Setup(item => item.GetRelativePath("/workspace", It.IsAny<string>()))
            .Returns((string _, string path) => path["/workspace/".Length..]);

        _path
            .Setup(item => item.GetFileName(It.IsAny<string>()))
            .Returns((string path) => Path.GetFileName(path));
    }

    [Theory]
    [InlineData("Generated.g.cs")]
    [InlineData("Generated.g.i.cs")]
    [InlineData("Generated.generated.cs")]
    [InlineData("Generated.designer.cs")]
    [InlineData("TemporaryGeneratedFile_Source.cs")]
    public async Task GIVEN_GeneratedFilename_WHEN_Classifying_THEN_ShouldIdentifyGeneratedSource(string filename)
    {
        var target = CreateTarget();
        var document = CreateDocument(filename, "internal sealed class Source;");

        var result = await target.IsGeneratedLookingAsync(
            document,
            "/workspace",
            TestContext.Current.CancellationToken);

        result.Should().BeTrue();
    }

    [Theory]
    [InlineData("// <auto-generated/>")]
    [InlineData("// <autogenerated>")]
    public async Task GIVEN_AutoGeneratedHeader_WHEN_Classifying_THEN_ShouldIdentifyGeneratedSource(string header)
    {
        var target = CreateTarget();
        var document = CreateDocument("Source.cs", $"{header}\ninternal sealed class Source;");

        var result = await target.IsGeneratedLookingAsync(
            document,
            "/workspace",
            TestContext.Current.CancellationToken);

        result.Should().BeTrue();
    }

    [Fact]
    public async Task GIVEN_OrdinarySource_WHEN_Classifying_THEN_ShouldNotIdentifyGeneratedSource()
    {
        var target = CreateTarget();
        var document = CreateDocument("Source.cs", "internal sealed class Source;");

        var result = await target.IsGeneratedLookingAsync(
            document,
            "/workspace",
            TestContext.Current.CancellationToken);

        result.Should().BeFalse();
    }

    [Fact]
    public async Task GIVEN_GeneratedFilenameTokenOnlyInDirectory_WHEN_Classifying_THEN_ShouldNotIdentifyGeneratedSource()
    {
        var target = CreateTarget();
        var document = CreateDocument(
            "Source.cs",
            "internal sealed class Source;",
            "/workspace/TemporaryGeneratedFile_Archive/Source.cs");

        var result = await target.IsGeneratedLookingAsync(
            document,
            "/workspace",
            TestContext.Current.CancellationToken);

        result.Should().BeFalse();
    }

    [Fact]
    public async Task GIVEN_MatchingException_WHEN_ClassifyingGeneratedFilename_THEN_ShouldNotIdentifyGeneratedSource()
    {
        _pathComparison
            .Setup(item => item.GetComparison("/workspace/generated/Generated.g.cs"))
            .Returns(StringComparison.OrdinalIgnoreCase);

        var target = CreateTarget(["generated\\*.G.CS"]);
        var document = CreateDocument("Generated.g.cs", "internal sealed class Source;", "/workspace/generated/Generated.g.cs");

        var result = await target.IsGeneratedLookingAsync(
            document,
            "/workspace",
            TestContext.Current.CancellationToken);

        result.Should().BeFalse();
        _pathComparison.Verify(
            item => item.GetComparison("/workspace/generated/Generated.g.cs"),
            Times.Once);
    }

    [Theory]
    [InlineData("Generated/*.g.cs", false)]
    [InlineData("generated/*.g.cs", true)]
    public async Task GIVEN_CaseSensitiveFileSystem_WHEN_MatchingException_THEN_ShouldRespectPathCase(
        string exception,
        bool expectedGenerated)
    {
        var target = CreateTarget([exception]);
        var document = CreateDocument(
            "Generated.g.cs",
            "internal sealed class Source;",
            "/workspace/Generated/Generated.g.cs");

        var result = await target.IsGeneratedLookingAsync(
            document,
            "/workspace",
            TestContext.Current.CancellationToken);

        result.Should().Be(expectedGenerated);
    }

    [Fact]
    public async Task GIVEN_PathlessGeneratedDocumentAndExceptions_WHEN_Classifying_THEN_ShouldUseFilename()
    {
        var target = CreateTarget(["generated/*.g.cs"]);
        var project = _workspace.CurrentSolution.AddProject("Project", "Project", LanguageNames.CSharp);
        var document = project.AddDocument("Generated.g.cs", SourceText.From("internal sealed class Source;"));

        var result = await target.IsGeneratedLookingAsync(
            document,
            "/workspace",
            TestContext.Current.CancellationToken);

        result.Should().BeTrue();
    }

    [Fact]
    public async Task GIVEN_HeaderMarkerAfterInspectionBoundary_WHEN_Classifying_THEN_ShouldNotIdentifyGeneratedSource()
    {
        var target = CreateTarget();
        var document = CreateDocument("Source.cs", $"{new string(' ', 2048)}// <auto-generated/>");

        var result = await target.IsGeneratedLookingAsync(
            document,
            "/workspace",
            TestContext.Current.CancellationToken);

        result.Should().BeFalse();
    }

    public void Dispose()
    {
        _workspace.Dispose();
    }

    private GeneratedSourceClassifier CreateTarget(IReadOnlyList<string>? exceptions = null)
    {
        var options = new WorkspaceOptions
        {
            GeneratedSourceExceptions = exceptions ?? [],
        };

        return new GeneratedSourceClassifier(
            Options.Create(options),
            _pathComparison.Object,
            _fileSystem.Object);
    }

    private Document CreateDocument(string name, string source, string? path = null)
    {
        var project = _workspace.CurrentSolution.AddProject("Project", "Project", LanguageNames.CSharp);
        return project.AddDocument(name, SourceText.From(source), filePath: path ?? $"/workspace/{name}");
    }
}
